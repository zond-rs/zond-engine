//! # The National Vulnerability Database feed
//!
//! Turns a year of NVD's JSON into a [`Catalogue`] the correlator can use, as
//! [`kev`](super::kev) does for CISA's feed. What NVD adds is versions: a KEV
//! entry names a vendor and a product, and an NVD record carries the CPE ranges a
//! vulnerability applies to. That is the difference between *this host runs Exim,
//! go and look* and *this host runs Exim 4.90, which is in the affected range*.
//!
//! ```no_run
//! use std::fs::File;
//! use std::io::BufReader;
//!
//! let file = File::open("CVE-2024.json")?;
//! let catalogue = zond_engine::import::nvd::read(&mut BufReader::new(file))?;
//! # Ok::<(), Box<dyn std::error::Error>>(())
//! ```
//!
//! ## Where the bytes come from
//!
//! NVD retired its JSON feeds at the end of 2023 for a rate-limited REST API, so
//! this reads the shape the community reconstruction publishes: an object
//! carrying a `timestamp` and a `cve_items` array. The 2.0 API returns the same
//! records a page at a time, and pages assembled into that shape read unchanged.
//!
//! The catalogue this crate ships, `assets/cve/nvd.toml`, is this module's output
//! over every year of that feed, regenerated by the `nvd_catalogue` example.
//!
//! ## Filtering by the corpus
//!
//! A converted KEV holds every entry CISA published, about twelve hundred. NVD is
//! three hundred and eighty thousand records naming several hundred thousand
//! products, and converting all of it would exceed [`MAX_DOCUMENT_BYTES`] by two
//! orders of magnitude.
//!
//! [`SignatureDb::versioned_products`] is every `vendor:product` a scan can name
//! *with a version*, and a record naming anything else is dropped as it is read.
//! An entry for software the fingerprint corpus cannot version has nothing to
//! match against, in the sense of
//! [`Reach::Unproduced`](crate::fingerprint::Reach), so nothing findable is lost.
//! Two hundred and sixty-nine products are named by some rule but never with a
//! version; keeping their entries would add a megabyte that cannot fire.
//!
//! ## Applications only
//!
//! An `o:` CPE's version is a release family (`microsoft:windows_server_2016`,
//! `linux:linux_kernel`), and a scan cannot read a kernel's patch level off the
//! wire. An entry keyed there fires on every host of that family and can be
//! neither confirmed nor denied. `linux:linux_kernel` alone accounts for eighteen
//! thousand CPE matches in one year of the feed. KEV already makes the
//! product-level claim at
//! [`Confidence::Weak`](crate::model::confidence::Confidence::Weak), so this
//! reader keeps `a:` records and skips `o:`.
//!
//! ## Streaming
//!
//! A year of NVD is about three hundred megabytes, so the array is walked element
//! by element and each record is converted and dropped before the next is read.
//! Peak memory is one record plus whatever survived the filter.
//!
//! ## One record, several entries
//!
//! The catalogue's `affected` grammar is a comma-joined *conjunction*: every
//! clause must hold. Disjoint ranges are common (CVE-2024-6387 affects OpenSSH
//! below 4.4 *and* from 8.5 to 9.8), so each range becomes its own entry under the
//! same CVE id, and each product a record names gets its own entries.
//!
//! ## Platform conditions are dropped
//!
//! NVD writes *vulnerable only when running on X* as a configuration whose nodes
//! are joined by `AND`: the vulnerable application in one, and the platform,
//! marked not vulnerable, in another. Apache HTTP Server's Windows-only flaws,
//! distribution patches to OpenSSH and vendor appliance builds are written this
//! way. A catalogue entry is judged against one service's CPE alone, so the
//! condition cannot be expressed, and the entry would charge every host running
//! the product with a flaw that exists on one platform.
//!
//! Such a configuration converts to nothing; a range the same record also states
//! unconditionally is kept. About one and a half percent of the entries the
//! shipped corpus admits come only from conditional configurations. The platforms
//! named are operating systems in three cases out of four, then hardware, then the
//! odd application (a Windows or Red Hat build, an F5 or SonicWall appliance), and
//! the platform's own advisories are the better source for those.

use std::collections::BTreeSet;
use std::fmt;
use std::io::BufRead;

use serde::de::{DeserializeSeed, IgnoredAny, MapAccess, SeqAccess, Visitor};
use serde::{Deserialize, Deserializer, Serialize};

use crate::cve::{Catalogue, CatalogueError, MAX_DOCUMENT_BYTES};
use crate::fingerprint::SignatureDb;

/// The id a converted catalogue carries.
///
/// The `zond:` namespace is reserved for what this crate ships and is refused on
/// anything read from outside, so a report traces a finding back to NVD.
pub const NVD_ID: &str = "nvd:cve";

/// The most of a feed this will read.
///
/// A hundred times [`MAX_DOCUMENT_BYTES`]: a year of NVD is three hundred
/// megabytes and converts to a few hundred kilobytes. The cap stops an endless
/// source; the input is streamed, so it is never held whole.
pub const MAX_FEED_BYTES: u64 = 100 * MAX_DOCUMENT_BYTES;

/// The longest `title` an entry carries.
///
/// A title is the description's first sentence, cut here if still long. Titles
/// are just under half of a converted document's bytes.
const MAX_TITLE_BYTES: usize = 160;

/// Why an NVD feed could not be converted.
#[non_exhaustive]
#[derive(Debug, thiserror::Error)]
pub enum NvdError {
    /// The bytes could not be read.
    #[error("the NVD feed could not be read: {0}")]
    Io(#[from] std::io::Error),

    /// The document is not the JSON this feed publishes.
    #[error("the NVD feed is malformed: {0}")]
    Malformed(String),

    /// The feed was longer than [`MAX_FEED_BYTES`].
    #[error("the NVD feed is longer than the {limit} byte limit")]
    TooLarge {
        /// The limit it passed.
        limit: u64,
    },

    /// More of the feed survived the filter than a catalogue document may hold.
    ///
    /// The feed itself was fine; the result is too large to read back. Convert
    /// one year at a time.
    #[error("{entries} entries convert to more than the {limit} byte document limit")]
    TooManyEntries {
        /// How many entries were kept.
        entries: usize,
        /// The document limit they did not fit in.
        limit: u64,
    },

    /// The catalogue reader refused the converted document, which is a defect in
    /// the conversion.
    #[error("the converted catalogue was refused: {0}")]
    Rejected(#[from] CatalogueError),
}

/// Converts the NVD JSON in `input` into the TOML document
/// [`Catalogue::read`] consumes.
///
/// The result carries the id [`NVD_ID`] and the feed's `timestamp` as its
/// version, so reports from two dumps of the feed are told apart.
///
/// Filtered against the shipped fingerprint corpus; see the module documentation.
///
/// # Errors
///
/// [`NvdError::Malformed`] for JSON that is not this feed,
/// [`NvdError::TooLarge`] past [`MAX_FEED_BYTES`], and
/// [`NvdError::TooManyEntries`] where what survived the filter will not fit in a
/// catalogue document.
pub fn to_document(input: &mut dyn BufRead) -> Result<String, NvdError> {
    to_document_for(input, SignatureDb::global().versioned_products())
}

/// [`to_document`], filtered against the given `vendor:product` keys.
///
/// For a caller who fingerprints with a corpus of their own, and for tests that
/// need a filter independent of the shipped corpus.
///
/// # Errors
///
/// The same as [`to_document`].
pub fn to_document_for(
    input: &mut dyn BufRead,
    products: &BTreeSet<String>,
) -> Result<String, NvdError> {
    // One byte past the cap, so the count can tell an oversized feed from one
    // that ends exactly at it.
    let bounded = std::io::Read::take(input, MAX_FEED_BYTES.saturating_add(1));
    let counted = Counting::new(bounded);
    let read = counted.read.clone();

    let mut deserializer = serde_json::Deserializer::from_reader(counted);
    let feed = Feed { products }
        .deserialize(&mut deserializer)
        .map_err(|error| NvdError::Malformed(error.to_string()))?;

    if read.get() > MAX_FEED_BYTES {
        return Err(NvdError::TooLarge {
            limit: MAX_FEED_BYTES,
        });
    }

    let document = Document {
        id: NVD_ID.to_string(),
        version: feed_version(&feed.timestamp),
        vulnerability: feed.vulnerability,
    };

    // Serialised so that quotes and backslashes in NVD's strings are escaped.
    let toml =
        toml::to_string(&document).map_err(|error| NvdError::Malformed(error.to_string()))?;

    if toml.len() as u64 > MAX_DOCUMENT_BYTES {
        return Err(NvdError::TooManyEntries {
            entries: document.vulnerability.len(),
            limit: MAX_DOCUMENT_BYTES,
        });
    }
    Ok(toml)
}

/// Reads the NVD JSON in `input` as a [`Catalogue`].
///
/// [`to_document`] followed by [`Catalogue::read`]. When scans are re-run against
/// the same feed, convert once with [`to_document`] and keep the result: the
/// conversion reads several hundred megabytes and produces a few hundred
/// kilobytes.
///
/// # Errors
///
/// Everything [`to_document`] returns, and [`NvdError::Rejected`] where the
/// document it produced was refused.
pub fn read(input: &mut dyn BufRead) -> Result<Catalogue, NvdError> {
    let document = to_document(input)?;
    Ok(Catalogue::read(&mut document.as_bytes())?)
}

/// The feed's `timestamp` as the catalogue grammar's `major.minor.patch`.
///
/// `2026-09-08T00:00:09+00:00` becomes `2026.9.8`. Anything unparseable becomes
/// `0.0.0`, which sorts below every real version.
fn feed_version(timestamp: &str) -> String {
    let date = timestamp.split('T').next().unwrap_or_default();
    let mut parts = date.split('-');

    let mut number = || -> Option<u32> { parts.next()?.parse().ok() };
    match (number(), number(), number()) {
        (Some(year), Some(month), Some(day)) => format!("{year}.{month}.{day}"),
        _ => "0.0.0".to_string(),
    }
}

/// A reader that remembers how much went through it.
///
/// `Read::take` stops at the limit without saying whether it was reached. The
/// count lets a feed cut off at the cap be reported as too large and not as
/// malformed JSON.
struct Counting<R> {
    inner: R,
    read: std::rc::Rc<std::cell::Cell<u64>>,
}

impl<R> Counting<R> {
    fn new(inner: R) -> Self {
        Self {
            inner,
            read: std::rc::Rc::new(std::cell::Cell::new(0)),
        }
    }
}

impl<R: std::io::Read> std::io::Read for Counting<R> {
    fn read(&mut self, buf: &mut [u8]) -> std::io::Result<usize> {
        let n = self.inner.read(buf)?;
        self.read.set(self.read.get().saturating_add(n as u64));
        Ok(n)
    }
}

/// The whole feed, deserialized against a filter.
///
/// A `DeserializeSeed` so the filter is applied while the array is walked, which
/// keeps only surviving records in memory.
struct Feed<'a> {
    products: &'a BTreeSet<String>,
}

/// The feed's timestamp and the entries that survived the filter.
struct Converted {
    timestamp: String,
    vulnerability: Vec<Entry>,
}

impl<'de> DeserializeSeed<'de> for Feed<'_> {
    type Value = Converted;

    fn deserialize<D: Deserializer<'de>>(self, deserializer: D) -> Result<Converted, D::Error> {
        deserializer.deserialize_map(self)
    }
}

impl<'de> Visitor<'de> for Feed<'_> {
    type Value = Converted;

    fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("an NVD feed object carrying `cve_items`")
    }

    fn visit_map<A: MapAccess<'de>>(self, mut map: A) -> Result<Converted, A::Error> {
        let mut timestamp = String::new();
        let mut vulnerability = Vec::new();
        let mut seen_items = false;

        while let Some(key) = map.next_key::<String>()? {
            match key.as_str() {
                "timestamp" => timestamp = map.next_value()?,
                "cve_items" | "vulnerabilities" => {
                    seen_items = true;
                    vulnerability = map.next_value_seed(Records {
                        products: self.products,
                    })?;
                }
                // Unknown keys are skipped: the feed grows fields.
                _ => {
                    map.next_value::<IgnoredAny>()?;
                }
            }
        }

        if !seen_items {
            return Err(serde::de::Error::missing_field("cve_items"));
        }
        Ok(Converted {
            timestamp,
            vulnerability,
        })
    }
}

/// The `cve_items` array, converted as it is walked.
struct Records<'a> {
    products: &'a BTreeSet<String>,
}

impl<'de> DeserializeSeed<'de> for Records<'_> {
    type Value = Vec<Entry>;

    fn deserialize<D: Deserializer<'de>>(self, deserializer: D) -> Result<Vec<Entry>, D::Error> {
        deserializer.deserialize_seq(self)
    }
}

impl<'de> Visitor<'de> for Records<'_> {
    type Value = Vec<Entry>;

    fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("an array of NVD records")
    }

    fn visit_seq<A: SeqAccess<'de>>(self, mut seq: A) -> Result<Vec<Entry>, A::Error> {
        let mut out = Vec::new();
        // One record in memory at a time, dropped once converted.
        while let Some(record) = seq.next_element::<Record>()? {
            entries_from(&record, self.products, &mut out);
        }
        Ok(out)
    }
}

/// One NVD record, cut down to what a catalogue entry needs.
///
/// The 2.0 API nests the record under a `cve` key and the reconstructed feed
/// does not; this type reads both. Every field defaults, because a record may
/// carry none of them: [`entries_from`] skips the ones it cannot convert.
#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct Record {
    /// The nested record of the 2.0 API's shape, absent in the feed's.
    cve: Option<Box<Record>>,
    #[serde(default)]
    id: String,
    #[serde(default)]
    vuln_status: String,
    #[serde(default)]
    descriptions: Vec<Description>,
    #[serde(default)]
    metrics: Metrics,
    #[serde(default)]
    weaknesses: Vec<Weakness>,
    #[serde(default)]
    configurations: Vec<Configuration>,
}

/// A string in one language, used for both a CVE's summary and a weakness's text.
/// The feed ships several languages and only English is read.
#[derive(Deserialize)]
struct Description {
    lang: String,
    value: String,
}

/// The CVSS scores a record carries, newest version first.
#[derive(Default, Deserialize)]
#[serde(rename_all = "camelCase")]
struct Metrics {
    #[serde(default)]
    cvss_metric_v31: Vec<Metric>,
    #[serde(default)]
    cvss_metric_v30: Vec<Metric>,
    #[serde(default)]
    cvss_metric_v2: Vec<Metric>,
}

/// One score.
///
/// `base_severity` appears in two places: CVSS 3.x puts it inside `cvssData`
/// beside the score, and CVSS 2, whose specification has no such field, has
/// NVD's own on the metric. Reading only the 3.x position would drop every record
/// scored under version 2 alone.
#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct Metric {
    #[serde(default)]
    base_severity: Option<String>,
    #[serde(default)]
    cvss_data: CvssData,
}

/// The `cvssData` object of a metric, holding the severity under CVSS 3.x. See
/// [`Metric`].
#[derive(Default, Deserialize)]
#[serde(rename_all = "camelCase")]
struct CvssData {
    #[serde(default)]
    base_severity: Option<String>,
}

/// A weakness the record cites. Its CWE identifier is the text of its
/// [`Description`].
#[derive(Deserialize)]
struct Weakness {
    #[serde(default)]
    description: Vec<Description>,
}

/// One configuration: the [`Node`]s naming the products and versions a record
/// applies to.
#[derive(Deserialize)]
struct Configuration {
    /// How the nodes combine: `AND` where every one must hold, and absent or
    /// `OR` where any one is enough.
    #[serde(default)]
    operator: Option<String>,
    #[serde(default)]
    nodes: Vec<Node>,
}

impl Configuration {
    /// Whether this configuration makes its vulnerable matches conditional on a
    /// platform: nodes joined by `AND`, one of which names nothing vulnerable.
    ///
    /// That node is the condition (*running on* an operating system, a device or
    /// another application). See the module documentation.
    fn is_platform_conditional(&self) -> bool {
        self.operator
            .as_deref()
            .is_some_and(|operator| operator.eq_ignore_ascii_case("and"))
            && self.nodes.iter().any(|node| {
                !node.cpe_match.is_empty()
                    && node.cpe_match.iter().all(|matched| !matched.vulnerable)
            })
    }
}

/// One node of a [`Configuration`], holding its CPE matches.
#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct Node {
    #[serde(default)]
    cpe_match: Vec<CpeMatch>,
}

/// One CPE the record says is affected, with the range it is affected over.
#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct CpeMatch {
    #[serde(default = "yes")]
    vulnerable: bool,
    #[serde(default)]
    criteria: String,
    version_start_including: Option<String>,
    version_start_excluding: Option<String>,
    version_end_including: Option<String>,
    version_end_excluding: Option<String>,
}

/// The serde default for [`CpeMatch::vulnerable`], which the feed omits when the
/// match is vulnerable and states only to say it is not.
fn yes() -> bool {
    true
}

/// The catalogue document, as [`Catalogue::read`] expects it.
#[derive(Serialize)]
struct Document {
    id: String,
    version: String,
    vulnerability: Vec<Entry>,
}

/// One catalogue entry.
#[derive(Serialize)]
struct Entry {
    cve: String,
    title: String,
    severity: String,
    vendor: String,
    product: String,
    affected: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    cwe: Option<u32>,
}

/// Converts one record into however many entries it yields, appending them.
///
/// Most records yield none: they name no product this corpus can version, carry
/// no severity, or are withdrawn.
fn entries_from(record: &Record, products: &BTreeSet<String>, out: &mut Vec<Entry>) {
    let record = record.cve.as_deref().unwrap_or(record);

    // A rejected CVE was withdrawn, but its ranges stay in the record.
    if record.vuln_status.eq_ignore_ascii_case("rejected") {
        return;
    }
    let (Some(severity), Some(title)) = (severity_of(record), title_of(record)) else {
        return;
    };
    let cwe = cwe_of(record);

    // NVD often repeats a range across configurations; a duplicate entry would
    // be reported twice.
    let mut seen = BTreeSet::new();
    for configuration in &record.configurations {
        if configuration.is_platform_conditional() {
            continue;
        }
        for node in &configuration.nodes {
            for matched in &node.cpe_match {
                let Some((vendor, product, affected)) = affected_range(matched, products) else {
                    continue;
                };
                if !seen.insert((vendor.clone(), product.clone(), affected.clone())) {
                    continue;
                }
                out.push(Entry {
                    cve: record.id.clone(),
                    title: title.clone(),
                    severity: severity.clone(),
                    vendor,
                    product,
                    affected,
                    cwe,
                });
            }
        }
    }
}

/// The `vendor`, `product` and `affected` clause one CPE match yields, where it
/// names something this corpus can version.
///
/// [`None`] for a CPE naming something else, one marked not vulnerable (it says
/// what must be *present* for the flaw), and one stating neither a range nor a
/// version.
fn affected_range(
    matched: &CpeMatch,
    products: &BTreeSet<String>,
) -> Option<(String, String, String)> {
    if !matched.vulnerable {
        return None;
    }

    // `cpe:2.3:a:vendor:product:version:...`, `a:` only. Split and unescaped as
    // the correlator reads a service's, so `7.03hp3\+ftf` names the release a
    // banner states.
    let fields = crate::cve::formatted_fields(matched.criteria.strip_prefix("cpe:2.3:")?);
    let mut parts = fields.iter().map(String::as_str);
    if parts.next()? != "a" {
        return None;
    }
    let vendor = parts.next()?;
    let product = parts.next()?;
    let version = parts.next()?;
    let update = parts.next().unwrap_or_default();

    let key = format!("{vendor}:{product}");
    if !products.contains(&key) {
        return None;
    }

    let clauses: Vec<String> = [
        (">=", &matched.version_start_including),
        (">", &matched.version_start_excluding),
        ("<=", &matched.version_end_including),
        ("<", &matched.version_end_excluding),
    ]
    .iter()
    .filter_map(|(op, bound)| {
        bound
            .as_ref()
            .map(|value| format!("{op} {}", unescaped(value)))
    })
    .collect();

    let affected = match clauses.is_empty() {
        // No range, so the CPE's version field is the claim. A wildcard there
        // means every release, which KEV's product-level entries cover.
        true if is_unset(version) => return None,
        // The 2.3 grammar puts a patch level in its own field, `6.6:p1`, where
        // banners and the URI form write `6.6p1`. Joined as the correlator joins
        // a service's CPE: `== 6.6` alone matches no OpenSSH ever shipped.
        true if is_unset(update) => format!("== {version}"),
        true => format!("== {version}{update}"),
        // The grammar has no clause for an update field beside a range (NVD
        // writes one rarely and inconsistently), so it is dropped, which can
        // only broaden the claim.
        false => clauses.join(", "),
    };
    Some((vendor.to_string(), product.to_string(), affected))
}

/// A value NVD wrote with the 2.3 grammar's escapes, unescaped. See
/// [`formatted_fields`](crate::cve::formatted_fields).
fn unescaped(value: &str) -> String {
    let mut plain = String::with_capacity(value.len());
    let mut characters = value.chars();
    while let Some(character) = characters.next() {
        match character {
            '\\' => plain.extend(characters.next()),
            other => plain.push(other),
        }
    }
    plain
}

/// Whether a CPE field states nothing: `*` is "any" and `-` is "not
/// applicable" in the 2.3 grammar, and an empty field is absent.
fn is_unset(field: &str) -> bool {
    matches!(field, "*" | "-" | "")
}

/// The severity a record carries, lowercased, from its newest scoring.
///
/// CVSS 3.1 over 3.0 over 2, as NVD shows it. [`None`] for a record
/// with no score, which is every record still awaiting analysis.
fn severity_of(record: &Record) -> Option<String> {
    [
        &record.metrics.cvss_metric_v31,
        &record.metrics.cvss_metric_v30,
        &record.metrics.cvss_metric_v2,
    ]
    .into_iter()
    .flatten()
    .find_map(|metric| {
        metric
            .cvss_data
            .base_severity
            .as_deref()
            .or(metric.base_severity.as_deref())
    })
    .map(str::to_ascii_lowercase)
}

/// The first sentence of the English description, as the entry's title, cut at
/// [`MAX_TITLE_BYTES`] and without its trailing full stop.
///
/// The first sentence almost always states what the vulnerability is; the rest
/// gives conditions.
fn title_of(record: &Record) -> Option<String> {
    let english = record
        .descriptions
        .iter()
        .find(|description| description.lang == "en")?;

    let mut title = String::with_capacity(MAX_TITLE_BYTES);
    let mut whitespace = false;
    for character in english.value.trim().chars() {
        if character.is_whitespace() {
            whitespace = !title.is_empty();
            continue;
        }
        if whitespace {
            // A sentence ends at `.`, `!` or `?` followed by whitespace, which
            // skips the dots inside `4.9.1`.
            if title.ends_with('.') || title.ends_with('!') || title.ends_with('?') {
                break;
            }
            title.push(' ');
            whitespace = false;
        }
        if title.len() + character.len_utf8() > MAX_TITLE_BYTES {
            break;
        }
        title.push(character);
    }

    let title = title.trim_end_matches(['.', ' ']).to_string();
    (!title.is_empty()).then_some(title)
}

/// The CWE a record names, where it names one as a number.
///
/// NVD also writes non-answers here (`NVD-CWE-noinfo`, `NVD-CWE-Other`,
/// `Unsure`), which are skipped. The first `CWE-` number wins; [`None`] if there
/// is none.
fn cwe_of(record: &Record) -> Option<u32> {
    record
        .weaknesses
        .iter()
        .flat_map(|weakness| weakness.description.iter())
        .filter(|description| description.lang == "en")
        .find_map(|description| description.value.strip_prefix("CWE-")?.parse().ok())
}

