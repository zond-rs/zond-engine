    /// End to end: a feed converts, reads back as a catalogue, and its range
    /// separates two hosts differing only in their exim version.
    ///
    /// `read` uses the shipped corpus, so this also checks that it admits exim.
    #[test]
    fn a_converted_range_tells_two_versions_apart() {
        use crate::model::host::Host;
        use crate::model::port::{Port, PortState, Protocol, Service};

        let catalogue = read(&mut EXIM.as_bytes()).expect("the feed reads as a catalogue");
        assert_eq!(catalogue.id(), NVD_ID);
        assert_eq!(catalogue.len(), 1);

        let matched = |version: &str| {
            let mut host = Host::new("192.0.2.1".parse().expect("an address"));
            let service = Service::new("smtp", 90).with_cpe(format!("cpe:/a:exim:exim:{version}"));
            host.add_port(Port::new(25, Protocol::Tcp, PortState::Open).with_service(service));
            crate::cve::correlate_with(&mut host, &catalogue);
            host.ports()
                .find(|port| port.number() == 25)
                .expect("the port")
                .findings()
                .any(|finding| finding.detection().id() == NVD_ID)
        };

        assert!(matched("4.90"), "4.90 is inside >= 4.87, <= 4.91");
        assert!(
            !matched("4.92"),
            "4.92 is past the range and must not match"
        );
    }

    /// A patch level NVD states in the CPE's `update` field is part of the
    /// release the entry names.
    ///
    /// NVD writes OpenSSH's `6.6:p1` where banners say `6.6p1`, and `== 6.6`
    /// would match no OpenSSH ever released. A service in either CPE spelling
    /// matches, and one at the release without the patch level does not. `-`
    /// and `*` add nothing.
    #[test]
    fn a_patch_level_in_the_update_field_is_part_of_the_version() {
        // A server-side flaw: the correlator withdraws client-side ones, which
        // would make the assertions below test that instead.
        const KEYBOARD_INTERACTIVE: &str = r#"{
          "timestamp": "2026-09-08T00:00:00+00:00",
          "cve_items": [{
            "id": "CVE-2015-5600",
            "descriptions": [{"lang": "en", "value": "keyboard-interactive devices allow unlimited retries."}],
            "metrics": {"cvssMetricV31": [{"cvssData": {"baseSeverity": "MEDIUM"}}]},
            "configurations": [{"nodes": [{"cpeMatch": [
              {"vulnerable": true, "criteria": "cpe:2.3:a:openbsd:openssh:6.6:p1:*:*:*:*:*:*"},
              {"vulnerable": true, "criteria": "cpe:2.3:a:openbsd:openssh:7.0:-:*:*:*:*:*:*"},
              {"vulnerable": true, "criteria": "cpe:2.3:a:openbsd:openssh:7.1:*:*:*:*:*:*:*"}
            ]}]}]
          }]
        }"#;

        let document = to_document_for(
            &mut KEYBOARD_INTERACTIVE.as_bytes(),
            &products(&["openbsd:openssh"]),
        )
        .expect("converts");
        assert!(document.contains(r#"affected = "== 6.6p1""#), "{document}");
        assert!(document.contains(r#"affected = "== 7.0""#), "{document}");
        assert!(document.contains(r#"affected = "== 7.1""#), "{document}");

        let catalogue = Catalogue::read(&mut document.as_bytes()).expect("reads back");
        let matched = |cpe: &str| {
            use crate::model::host::Host;
            use crate::model::port::{Port, PortState, Protocol, Service};

            let mut host = Host::new("192.0.2.1".parse().expect("an address"));
            let service = Service::new("ssh", 90).with_cpe(cpe);
            host.add_port(Port::new(22, Protocol::Tcp, PortState::Open).with_service(service));
            crate::cve::correlate_with(&mut host, &catalogue);
            host.ports()
                .find(|port| port.number() == 22)
                .expect("the port")
                .findings()
                .any(|finding| finding.detection().id() == NVD_ID)
        };

        assert!(matched("cpe:/a:openbsd:openssh:6.6p1"), "the URI form");
        assert!(
            matched("cpe:2.3:a:openbsd:openssh:6.6:p1:*:*:*:*:*:*"),
            "the 2.3 form"
        );
        assert!(
            !matched("cpe:/a:openbsd:openssh:6.6"),
            "a release without the patch level is not the one named"
        );
    }

